import assert from 'node:assert/strict';
import {chromium} from 'playwright';
const base='http://127.0.0.1:8765/';
const browser=await chromium.launch({headless:true});
const errors=[];
const visit=async(page,path)=>{const r=await page.goto(base+path,{waitUntil:'domcontentloaded'});assert(r?.ok(),'HTTP response failed for '+path);};
try{
 const desktop=await browser.newPage({viewport:{width:1366,height:850}});
 desktop.on('pageerror',err=>errors.push('desktop: '+err.message));
 await visit(desktop,'index.html');
 assert.match(await desktop.locator('h1').innerText(),/今の保存方法/);
 assert.equal(await desktop.locator('#productGrid').count(),0,'catalog on homepage forbidden');
 assert.equal(await desktop.locator('.problem-row').count(),3);
  await desktop.waitForFunction(() => document.querySelector('.hero-photo img')?.complete, null, {timeout:15000});
  assert((await desktop.locator('.hero-photo img').evaluate(img => img.naturalWidth)) > 0, 'hero photo is not loaded');
 await desktop.screenshot({path:'journey-home-desktop.png',fullPage:true});
 await desktop.locator('.problem-row').first().click();
 await desktop.waitForURL(/start.html\?goal=share/);
 assert.match(await desktop.locator('#wizardTitle').innerText(),/何を解決したいですか/);
 await desktop.locator('[data-action="next"]').click();
 assert.match(await desktop.locator('#wizardTitle').innerText(),/どのくらい/);
 await desktop.locator('#field_people').selectOption('medium');
 await desktop.locator('#field_capacity').selectOption('small');
 await desktop.locator('#field_remote').selectOption('yes');
 await desktop.locator('[data-action="next"]').click();
 await desktop.locator('#field_already').selectOption('m365');
 await desktop.locator('#field_admin').selectOption('no');
 await desktop.locator('#field_backup').selectOption('none');
 await desktop.locator('[data-action="next"]').click();
 assert.match(await desktop.locator('#wizardTitle').innerText(),/保存環境の整理結果/);
 assert.match(await desktop.locator('#wizardContent').innerText(),/追加契約は不要/);
 assert.match(await desktop.locator('#wizardContent').innerText(),/復元できるバックアップ/);
 assert.equal(await desktop.locator('.spec-item').count(),3);
 assert.match(await desktop.locator('#estimateYear').innerText(),/未入力/);
 await desktop.locator('#deviceCost').fill('0');
 await desktop.locator('#setupCost').fill('11000');
 await desktop.locator('#monthlyCost').fill('3300');
 assert.match(await desktop.locator('#estimateYear').innerText(),/50,600円/);
 await desktop.screenshot({path:'journey-result-desktop.png',fullPage:true});
 await desktop.locator('a[href^="compare.html?kind="]').click();
 await desktop.waitForURL(/compare.html/);
 assert.equal(await desktop.locator('.catalog-item').count(),3,'cloud filter from wizard');
 await desktop.locator('button[data-kind="all"]').click();
 assert.equal(await desktop.locator('.catalog-item').count(),8);
 await desktop.locator('input[data-compare="synology"]').check();
 await desktop.locator('input[data-compare="buffalo-nas"]').check();
 assert.match(await desktop.locator('#compareTable').innerText(),/DS225\+/);
 await visit(desktop,'learn.html');
 assert.match(await desktop.locator('#purpose').innerText(),/バックアップ/);
 assert.match(await desktop.locator('#costs').innerText(),/費用/);
 const mobile=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1});
 mobile.on('pageerror',err=>errors.push('mobile: '+err.message));
 for(const path of ['index.html','start.html','learn.html','compare.html']){
  await visit(mobile,path);
  const metrics=await mobile.evaluate(()=>({body:document.documentElement.scrollWidth,width:window.innerWidth}));
  assert(metrics.body<=metrics.width+3,path+' horizontal overflow '+JSON.stringify(metrics));
 }
 await mobile.screenshot({path:'journey-mobile.png',fullPage:true});
 assert.equal(errors.length,0,'JS page errors: '+errors.join('; '));
 console.log('PASS: homepage, learning, 4-stage diagnosis, existing-service checks, missing-price rule, manual estimate, handoff and mobile layout.');
}finally{await browser.close();}
