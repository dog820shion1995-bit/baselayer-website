 await page.locator('[data-action="next"]').click();
 await page.locator('#f_backup').selectOption('none');
 await page.locator('#f_rto').selectOption('hour');
 await page.locator('#f_rpo').selectOption('day');
 await page.locator('#f_critical').selectOption('high');
 await page.locator('#f_admin').selectOption('no');
 await page.locator('#f_sensitive').selectOption('normal');
 await page.locator('[data-action="next"]').click();
 assert.match(await page.locator('#wizardTitle').innerText(),/導入判断レポート/);
 const body=await page.locator('#wizardContent').innerText();
 assert.match(body,/新規契約は不要/);
 assert.match(body,/バックアップ/);
 assert.match(body,/比較候補にする理由/);
 assert.match(body,/専門家/);
 await page.locator('[data-view="technical"]').click();
 assert.equal(await page.locator('.report-technical').isVisible(),true);
 assert.equal(await page.locator('.report-owner').isVisible(),false);
 await page.locator('[data-view="sales"]').click();
 assert.equal(await page.locator('.report-sales').isVisible(),true);
 await page.locator('[data-view="owner"]').click();
 await page.locator('#chooseProduct').selectOption('xserver');
 assert.match(await page.locator('#officialPrice').innerText(),/3,300円/);
 assert.match(await page.locator('#sumInitial').innerText(),/50,600円/);
 assert.match(await page.locator('#sumYear').innerText(),/50,600円/);
 assert.match(await page.locator('#sumThree').innerText(),/129,800円/);
 await page.locator('#extraInitial').fill('11000');
 await page.locator('#extraMonthly').fill('3300');
 assert.match(await page.locator('#sumThree').innerText(),/259,600円/);
 await page.locator('#chooseProduct').selectOption('zoho');
 assert.match(await page.locator('#sumYear').innerText(),/価格未確認/);
 assert.match(await page.locator('#costNote').innerText(),/米ドル/);
 await page.screenshot({path:'decision-report.png',fullPage:true});
 await goto(page,'price-guide.html');
 assert.equal(await page.locator('#cloudPrices .catalog-item').count(),3);
 assert.equal(await page.locator('#devicePrices .catalog-item').count(),5);
 assert.match(await page.locator('#cloudPrices').innerText(),/3,300円/);
 await goto(page,'product.html?id=buffalo-nas');
 assert.match(await page.locator('#detailBody').innerText(),/RAID1/);
 assert.match(await page.locator('#detailBody').innerText(),/Synology/);
 assert.match(await page.locator('#detailBody').innerText(),/他の製品と何が違う/);
 assert.equal(await page.locator('.product-media-panel img').count(),1,'BUFFALO product image absent');
