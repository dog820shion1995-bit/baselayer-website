import assert from 'node:assert/strict';
import { chromium } from 'playwright';

const origin = 'http://127.0.0.1:8765/';
const browser = await chromium.launch({headless:true});
const errors = [];
try {
  const page = await browser.newPage({viewport:{width:1440,height:900},deviceScaleFactor:1});
  page.on('pageerror',err=>errors.push('desktop: '+err.message));
  const response = await page.goto(origin,{waitUntil:'networkidle'});
  assert(response?.ok(),'homepage unavailable');
  assert.match(await page.locator('h1').innerText(),/大切なデータ/);
  await page.locator('.product-card').first().waitFor();
  assert.equal(await page.locator('.product-card').count(),8,'initial products');
  await page.locator('[data-category="nas"]').click();
  assert.equal(await page.locator('.product-card').count(),2,'NAS category');
  await page.locator('[data-filter="all"]').click();
  await page.locator('#catalogSearch').fill('DS225+');
  assert.equal(await page.locator('.product-card').count(),1,'model search');
  await page.locator('#catalogSearch').fill('');
  await page.locator('button[data-detail="synology"]').click();
  assert.equal(await page.locator('#detailDialog').evaluate(el=>el.open),true,'detail dialog');
  assert.match(await page.locator('#detailContent').innerText(),/対応HDD/);
  await page.locator('[data-close="detailDialog"]').click();
  await page.locator('button[data-toggle="synology"]').click();
  await page.locator('button[data-toggle="buffalo-nas"]').click();
  assert.equal(await page.locator('#compareTray').isVisible(),true,'comparison tray');
  await page.locator('#trayOpen').click();
  assert.equal(await page.locator('#compareDialog').evaluate(el=>el.open),true,'comparison dialog');
  assert.match(await page.locator('#compareContent').innerText(),/DiskStation/);
  assert.match(await page.locator('#compareContent').innerText(),/LinkStation/);
  await page.locator('[data-close="compareDialog"]').click();
  await page.locator('#advisorForm button[type="submit"]').click();
  assert.match(await page.locator('#advisorResult').innerText(),/クラウドストレージ/);
  await page.locator('button[data-topic="cloud"]').click();
  assert.match(await page.locator('#guideContent').innerText(),/クラウドストレージとは/);
  await page.locator('[data-close="guideDialog"]').click();
  await page.locator('#clearCompare').click();
  await page.evaluate(()=>scrollTo(0,0));
  assert.equal(await page.locator('.header').isVisible(),true,'desktop header');
  await page.screenshot({path:'storage-home-desktop.png',fullPage:true});
  const mobile = await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1});
  mobile.on('pageerror',err=>errors.push('mobile: '+err.message));
  await mobile.goto(origin,{waitUntil:'networkidle'});
  await mobile.locator('.product-card').first().waitFor();
  assert.equal(await mobile.locator('.product-card').count(),8,'mobile initial products');
  await mobile.locator('#menuToggle').click();
  assert.equal(await mobile.locator('#menuToggle').getAttribute('aria-expanded'),'true');
  await mobile.locator('#mobileMenu a[href="#advisor"]').click();
  assert.equal(await mobile.locator('#menuToggle').getAttribute('aria-expanded'),'false');
  await mobile.locator('#memberCount').selectOption('5');
  await mobile.locator('#advisorForm button[type="submit"]').click();
  assert.match(await mobile.locator('#advisorResult').innerText(),/クラウドストレージ/);
  await mobile.evaluate(()=>scrollTo(0,0));
  assert.equal(await mobile.locator('.header').isVisible(),true,'mobile header');
  assert.equal(await mobile.evaluate(()=>document.documentElement.scrollWidth <= window.innerWidth + 1),true,'mobile has horizontal overflow');
  await mobile.screenshot({path:'storage-home-mobile.png',fullPage:true});
  await mobile.goto(origin+'storage-policy.html',{waitUntil:'domcontentloaded'});
  assert.match(await mobile.locator('h1').innerText(),/掲載・広告/);
  await mobile.close();
  await page.close();
  assert.equal(errors.length,0,errors.join('; '));
  console.log('PASS: desktop & mobile browser flows, 8 cards, search, category, advisor, dialogs, compare, privacy policy. Screenshots saved.');
} finally {
  await browser.close();
}
