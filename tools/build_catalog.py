#!/usr/bin/env python3
"""Build the offline-compatible catalog. No network requests, no invented specifications."""
import json, pathlib, re, sys
ROOT=pathlib.Path(__file__).resolve().parents[1]
DATA=ROOT/'data/products.json'
OUT=ROOT/'product-data.js'
CATEGORIES={'router','switch','ap','firewall','lan','fiber','cable','pc','server','storage','monitor','peripheral','printer','meeting','power','rack'}
def main():
    items=json.loads(DATA.read_text(encoding='utf-8'))
    assert isinstance(items,list)
    seen=set(); verified=0; missing=[]
    for i,p in enumerate(items,1):
        for key in ('model','brand','cat','category'):
            if not isinstance(p.get(key),str) or not p[key].strip():raise ValueError(f'row {i}: missing {key}')
        if p['cat'] not in CATEGORIES:raise ValueError(f'{p["model"]}: unknown category')
        key=(p['brand'].casefold(),re.sub(r'[^a-z0-9]','',p['model'].casefold()))
        if key in seen:raise ValueError(f'duplicate {p["brand"]} {p["model"]}')
        seen.add(key)
        specs=p.get('specs',{})
        if not isinstance(specs,dict) or any(not isinstance(k,str) or not isinstance(v,str) or not v.strip() for k,v in specs.items()):raise ValueError(f'{p["model"]}: bad specs')
        if specs:
            if not p.get('source','').startswith('https://'):raise ValueError(f'{p["model"]}: specs require official source URL')
            if not re.fullmatch(r'\d{4}-\d{2}-\d{2}',p.get('checked','')):raise ValueError(f'{p["model"]}: specs require checked date YYYY-MM-DD')
            verified+=1
        else:missing.append(p['model'])
    OUT.write_text('/* Generated by tools/build_catalog.py; edit data/products.json instead. */\nwindow.BASELAYER_PRODUCTS = '+json.dumps(items,ensure_ascii=False,separators=(',',':'))+';\n',encoding='utf-8')
    print(f'Validated {len(items)} models; {verified} with sourced specs; {len(missing)} pending. Generated {OUT.name}.')
    print('Pending:',', '.join(missing))
if __name__=='__main__':
    try:main()
    except (ValueError,AssertionError) as e:print('ERROR:',e,file=sys.stderr);sys.exit(1)
